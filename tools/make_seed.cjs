// Builds supabase/seed_places.sql from js/places.js so the app and the
// database start from the same demo records.  Run: node tools/make_seed.cjs
const fs = require("fs"), path = require("path"), vm = require("vm");
const root = path.join(__dirname, "..");
const ctx = { window: {} }; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, "js/places.js"), "utf8"), ctx);
const W = ctx.window.W;
const q = (v) => v === null || v === undefined ? "null" : "'" + String(v).replace(/'/g, "''") + "'";
const arr = (a) => "array[" + (a || []).map(q).join(",") + "]::text[]";
const js = (o) => q(JSON.stringify(o || {})) + "::jsonb";
const rows = W.DEMO_PLACES.map((p) => {
  const wc = {};
  const map = { stepFree: "step_free", ramp: "ramp", interior: "interior", groundFloor: "ground_floor", lift: "lift", toilet: "accessible_toilet" };
  for (const [k, v] of Object.entries(p.wheelchair || {})) if (map[k]) wc[map[k]] = v;
  return `(${[q(p.id), q(p.status), q(p.name.en), q(p.name.ar), q(p.cat), q(p.kind), q(p.area),
    p.price ? p.price.amount : "null", q(p.price && p.price.basis), q(p.includes.transport), q(p.includes.taxes),
    q(p.pets.policy), arr(p.pets.types), js(wc), arr(p.access), arr(p.tags), q(p.note && p.note.en), q(p.note && p.note.ar)].join(", ")})`;
});
const sql = `-- Demo places (fictional). Generated by tools/make_seed.cjs from js/places.js.
-- These rows stay record_status = 'demo' and are never shown as verified.
insert into public.places (id, record_status, name_en, name_ar, category, kind, area,
  price_amount, price_basis, includes_transport, includes_taxes,
  pet_policy, pet_types, wheelchair, access_features, tags, note_en, note_ar)
values
${rows.join(",\n")}
on conflict (id) do nothing;
`;
fs.writeFileSync(path.join(root, "supabase/seed_places.sql"), sql);
console.log("wrote supabase/seed_places.sql with", rows.length, "demo places");
